def seed_database(silent=False):
    """Seed the database with realistic sample government jobs."""
    init_db()
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT COUNT(*) as count FROM jobs;")
    count = cursor.fetchone()['count']
    conn.close()

    if count == 0:
        if not silent:
            print("Seeding initial government job notifications...")
        for job in SAMPLE_JOBS:
            process_job_notification(job)
        
        # Mark UPPSC as an extended corrigendum example
        conn = get_db_connection()
        conn.execute("""
            UPDATE jobs 
            SET is_extended = 1, original_deadline = '2026-10-15 18:00:00',
                corrigendum_note = 'Deadline officially extended from 15-Oct-2026 to 25-Oct-2026 via Corrigendum Notice No. 89/Corrigendum/2026.'
            WHERE advt_no = 'A-2/E-1/2026'
        """)
        conn.commit()
        conn.close()
        if not silent:
            print(f"Successfully seeded {len(SAMPLE_JOBS)} government jobs!")
    else:
        if not silent:
            print(f"Database already contains {count} jobs. Skipping seed.")

if __name__ == "__main__":
    seed_database()
